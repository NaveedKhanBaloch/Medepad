"""Picks a short, meaningful consultation name from the conversation (no AI needed).

It looks for the word pairs and words that are repeated most, e.g. "Back pain & physical therapy".
When notes are generated by the language model, its own title replaces this one."""
import re
from collections import Counter

STOPWORDS = set(
    """
    a about above after again against all also am an and any are as at be because been before being below
    between both but by can could did do does doing done down during each few for from further get gets got
    had has have having he her here hers herself him himself his how i if in into is it its itself just let
    lets me more most much must my myself no nor not now of off on once only or other our ours ourselves out
    over own same she should so some such than that the their theirs them themselves then there these they
    this those through to too under until up very was we were what when where which while who whom why will
    with would you your yours yourself yourselves yes yeah okay ok oh um uh hmm like well right really thing
    things something anything nothing everything someone anyone time today going gonna want wanna know think
    thought feel felt say said tell told see look make made take took give gave come came still bit little
    lot lots maybe sure good fine thanks thank please hello hi bye doctor patient also kind sort mean actually
    speaker speakers guest
    """.split()
)


def suggest_title(text: str, max_parts: int = 2) -> str | None:
    words = [w.strip("'").lower() for w in re.findall(r"[^\W\d_]+(?:'[^\W\d_]+)?", text or "")]
    keep = [w if len(w) >= 3 and w not in STOPWORDS else None for w in words]
    pairs = Counter((a, b) for a, b in zip(keep, keep[1:]) if a and b and a != b)
    singles = Counter(w for w in keep if w)

    parts: list[str] = []
    used: set[str] = set()
    for (a, b), count in pairs.most_common():
        if count < 2 or len(parts) >= max_parts:
            break
        if a in used or b in used:
            continue
        parts.append(f"{a} {b}")
        used |= {a, b}
    for word, count in singles.most_common():
        if len(parts) >= max_parts or count < 2:
            break
        if word not in used:
            parts.append(word)
            used.add(word)
    if not parts:
        return None
    title = " & ".join(parts)
    return title[0].upper() + title[1:]
